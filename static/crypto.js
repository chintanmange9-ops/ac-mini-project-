  const xor = (a, b) => a.map((v, i) => v ^ b[i]);
  const rotl1 = b => ((b << 1) | (b >> 7)) & 0xFF;
  const rotr1 = b => ((b >> 1) | (b << 7)) & 0xFF;

  function roundKeys() {
    const out = [];
    for (let r = 0; r < ROUNDS; r++) {
      const s = (r * 3) % 16;
      const d = MASTER_KEY.slice(s).concat(MASTER_KEY.slice(0, s));
      out.push([d.slice(0, 8), d.slice(8, 16)]);
    }
    return out;
  }
  const RK = roundKeys();

  function vigenere(block, dec) {
    return block.map((b, i) => dec ? (b - MASTER_KEY[i] + 256) % 256 : (b + MASTER_KEY[i]) % 256);
  }
  function aesEngine(rhs, rk, dec) {
    if (!dec) {
      const s = xor(rhs, rk).map(b => SBOX[b]);
      return [s[0], s[3], s[2], s[5], s[4], s[7], s[6], s[1]];
    }
    const u = [rhs[0], rhs[7], rhs[2], rhs[1], rhs[4], rhs[3], rhs[6], rhs[5]];
    return xor(u.map(b => INV_SBOX[b]), rk);
  }
  function desEngine(lhs, rk) { return xor(lhs, rk).map(b => rotl1(b ^ 0x55)); }
  function desInverse(lhs, rk) { return xor(lhs.map(b => rotr1(b) ^ 0x55), rk); }

  function blockEncrypt(block) {
    let l = block.slice(0, 8), r = block.slice(8, 16);
    for (let q = 0; q < ROUNDS; q++) {
      l = desEngine(l, RK[q][0]);
      r = aesEngine(r, RK[q][1], false);
      if (q < ROUNDS - 1) { const t = l; l = r; r = t; }
    }
    return l.concat(r);
  }
  function blockDecrypt(block) {
    let l = block.slice(0, 8), r = block.slice(8, 16);
    for (let q = ROUNDS - 1; q >= 0; q--) {
      if (q < ROUNDS - 1) { const t = l; l = r; r = t; }
      r = aesEngine(r, RK[q][1], true);
      l = desInverse(l, RK[q][0]);
    }
    return l.concat(r);
  }
  function pad(data) {
    const n = 16 - (data.length % 16);
    return data.concat(new Array(n).fill(n));
  }
  function unpad(data) {
    if (!data.length) throw new Error("bad padding");
    const n = data[data.length - 1];
    if (n < 1 || n > 16) throw new Error("bad padding");
    return data.slice(0, data.length - n);
  }
  function tesEncryptBytes(plain, iv) {
    const padded = pad(Array.from(plain));
    const out = Array.from(iv);
    let prev = Array.from(iv);
    for (let i = 0; i < padded.length; i += 16) {
      const blk = padded.slice(i, i + 16);
      const cb = vigenere(xor(blk, prev), false);
      const enc = blockEncrypt(cb);
      out.push(...enc);
      prev = enc;
    }
    return out;
  }
  function tesDecryptBytes(blob) {
    if (blob.length < 32 || blob.length % 16 !== 0) throw new Error("bad TES layout");
    const iv = blob.slice(0, 16);
    const out = [];
    let prev = iv;
    for (let i = 16; i < blob.length; i += 16) {
      const enc = blob.slice(i, i + 16);
      const e = blockDecrypt(enc);
      const cb = vigenere(e, true);
      out.push(...xor(cb, prev));
      prev = enc;
    }
    return unpad(out);
  }
  function b64e(bytes) {
    let s = "";
    for (let i = 0; i < bytes.length; i += 0x8000) {
      s += String.fromCharCode.apply(null, bytes.slice(i, i + 0x8000));
    }
    return btoa(s);
  }
  function b64d(b64) {
    const s = atob(b64);
    const out = new Array(s.length);
    for (let i = 0; i < s.length; i++) out[i] = s.charCodeAt(i);
    return out;
  }
  function hex(bytes) { return bytes.map(b => b.toString(16).padStart(2, "0")).join(""); }

  function randomIV() {
    const a = new Uint8Array(16);
    crypto.getRandomValues(a);
    return b64e(Array.from(a));
  }
  function encryptField(plaintext, ivB64) {
    const blob = tesEncryptBytes(Array.from(new TextEncoder().encode(plaintext)), b64d(ivB64));
    return b64e(blob);
  }
